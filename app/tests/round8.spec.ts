import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { mkdir } from 'node:fs/promises';
const token = readFileSync('../.env.local','utf8').match(/^OPERATOR_TOKEN=(.+)$/m)![1].trim();
test.use({baseURL:'http://127.0.0.1:5174',launchOptions:{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE,args:['--use-angle=d3d11']}});
test.beforeEach(async({page})=>{await page.addInitScript((token)=>sessionStorage.setItem('drain-operator',JSON.stringify({token,name:'Browser check'})),token);});
test('storm board calculates five assets and selects their map marker',async({page})=>{
  test.setTimeout(180000);
  await mkdir('../docs/screens/round8',{recursive:true});
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Set the storm to compare'})).toBeVisible();
  await page.getByRole('button',{name:'Run storm',exact:true}).click();
  await expect(page.locator('.triage-row')).toHaveCount(5,{timeout:150000});
  await expect(page.locator('.triage-row').filter({hasText:'S2'})).toContainText('Capacity-limited: escalate to owner');
  await expect(page.locator('.triage-rows')).not.toContainText('T1');
  await page.getByRole('button',{name:'Plan',exact:true}).click();
  await page.locator('.triage-asset').filter({hasText:'R1'}).click();
  await expect(page.locator('.triage-row.selected')).toContainText('R1');
  await page.screenshot({path:'../docs/screens/round8/board-storm.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
});
